def tech_by_id():
    return {t["id"]: t for t in TECHNIQUES}

def test_by_id():
    return {t[0]: dict(id=t[0], name=t[1], clean=t[2], fails=t[3]) for t in TESTS}

def check():
    """Consistency: every referenced technique and test exists; returns (n_techniques, n_problems, n_causes)."""
    ids = tech_by_id(); tests = test_by_id(); n = 0
    assert len(ids) == len(TECHNIQUES), "duplicate technique ids"
    for p in PROBLEMS:
        for c in p["causes"]:
            n += 1
            assert c["test"] in tests, (p["id"], c["test"])
            for t in c["techniques"]: assert t in ids, (p["id"], c["id"], t)
    return len(TECHNIQUES), len(PROBLEMS), n
